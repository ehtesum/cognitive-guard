"""
CognitiveGuard: Complete Unified Defense Middleware Pipeline
Coordinates:
    - Module 1: Belief Trajectory & Logit Acceleration Tracker
    - Module 2: Causal DAG Provenance Pruner
    - Module 3: Adaptive Counter-Prompt Immunizer
"""

from typing import List, Dict, Any, Optional, Tuple
from dataclasses import dataclass
import json
import time

from .belief_tracker import BeliefTrajectoryTracker, TrajectoryStep
from .causal_dag import CausalDAGPruner, AuditReport
from .counter_prompt import AdaptiveCounterPromptImmunizer, ImmunizationPrompt


@dataclass
class DefenseDecision:
    attack_detected: bool
    module1_alert: bool
    module2_alert: bool
    provenance_ratio: float
    peak_acceleration: float
    peak_accel_step: int
    pruned_edges_count: int
    immunization_triggered: bool
    counter_prompt: str
    execution_time_ms: float
    audit_summary: Dict[str, Any]


class CognitiveGuardPipeline:
    """
    Unified defense middleware that sits between the untrusted evidence feed
    and the downstream victim LLM analyst.
    """

    def __init__(
        self,
        acceleration_threshold: float = 0.25,
        provenance_threshold: float = 0.65,
        strictness_level: str = "balanced"
    ):
        self.tracker = BeliefTrajectoryTracker(
            acceleration_threshold=acceleration_threshold,
            adaptive_threshold=True
        )
        self.pruner = CausalDAGPruner(
            provenance_threshold=provenance_threshold
        )
        self.immunizer = AdaptiveCounterPromptImmunizer(
            strictness_level=strictness_level
        )

    def reset(self):
        """Reset internal state for a new session."""
        self.tracker.reset()

    def inspect_feed_and_reasoning(
        self,
        posts: List[Dict[str, Any]],
        step_beliefs: Optional[List[float]] = None,
        preliminary_rationale: Optional[str] = None,
        target_hypothesis: Optional[str] = None
    ) -> DefenseDecision:
        """
        Execute full CognitiveGuard defense audit across all three modules.

        Args:
            posts: Chronological list of input evidence posts.
            step_beliefs: Optional list of posterior beliefs P(H_f | E_{1:t}) per post step.
            preliminary_rationale: The intermediate Chain-of-Thought reasoning generated by the model.
            target_hypothesis: The specific target claim being evaluated.

        Returns:
            DefenseDecision containing verdict, metrics, pruned graph, and counter-prompt.
        """
        start_time = time.perf_counter()
        self.reset()

        # Step 1: Run Module 1 (Belief Trajectory Tracking)
        module1_alert = False
        peak_accel = 0.0
        peak_step = 0
        last_step = None

        if step_beliefs:
            for i, p in enumerate(posts):
                b = step_beliefs[i] if i < len(step_beliefs) else step_beliefs[-1]
                step = self.tracker.update(
                    belief_prob=b,
                    post_id=p.get("post_id", i+1),
                    metadata={"sequencing_role": p.get("sequencing_role", "evidence")}
                )
                if step.is_anomaly:
                    module1_alert = True
                last_step = step

            summary = self.tracker.get_trajectory_summary()
            peak_accel = summary.get("peak_acceleration", 0.0)
            peak_step = summary.get("peak_acceleration_step", 0)

        # Step 2: Run Module 2 (Causal DAG Provenance Audit)
        module2_alert = False
        audit_report = None

        self.pruner.build_evidence_graph(posts)
        if preliminary_rationale:
            self.pruner.extract_cot_causal_dag(preliminary_rationale)
            audit_report = self.pruner.audit_provenance(target_hypothesis=target_hypothesis)
            module2_alert = audit_report.is_manipulated
        else:
            audit_report = AuditReport(
                total_inferred_edges=0,
                grounded_edges=0,
                hallucinated_edges=0,
                provenance_ratio=1.0,
                is_manipulated=False,
                pruned_edges=[],
                critical_unsupported_claims=[]
            )

        # Step 3: Run Module 3 (Adaptive Immunization)
        overall_attack_detected = module1_alert or module2_alert
        immunization = self.immunizer.generate_immunization(
            trajectory_step=last_step if module1_alert else None,
            audit_report=audit_report,
            target_hypothesis=target_hypothesis
        )

        execution_time_ms = round((time.perf_counter() - start_time) * 1000, 2)

        return DefenseDecision(
            attack_detected=overall_attack_detected,
            module1_alert=module1_alert,
            module2_alert=module2_alert,
            provenance_ratio=audit_report.provenance_ratio,
            peak_acceleration=peak_accel,
            peak_accel_step=peak_step,
            pruned_edges_count=audit_report.hallucinated_edges,
            immunization_triggered=immunization.is_triggered,
            counter_prompt=immunization.counter_prompt,
            execution_time_ms=execution_time_ms,
            audit_summary={
                "trigger_reasons": immunization.trigger_reasons,
                "unsupported_claims": audit_report.critical_unsupported_claims
            }
        )

    def print_decision_report(self, decision: DefenseDecision):
        """Print full summary report of the defense decision."""
        print("\n" + "=" * 80)
        print("COGNITIVEGUARD: UNIFIED DEFENSE DECISION & INTERVENTION TELEMETRY")
        print("=" * 80)
        status_str = "[THREAT DETECTED: COGNITIVE COLLUSION ATTACK]" if decision.attack_detected else "[CLEAN FEED: BENIGN REASONING]"
        print(f"Overall Defense Verdict:     {status_str}")
        print(f"Module 1 Alert (Logit Accel): {decision.module1_alert} (Peak a = {decision.peak_acceleration} at Step #{decision.peak_accel_step})")
        print(f"Module 2 Alert (Causal DAG):  {decision.module2_alert} (Provenance eta = {decision.provenance_ratio:.3f}, Pruned = {decision.pruned_edges_count})")
        print(f"Module 3 Triggered:           {decision.immunization_triggered}")
        print(f"Total Execution Latency:      {decision.execution_time_ms} ms (< 250 ms target)")
        print("-" * 80)
        if decision.immunization_triggered:
            print("Targeted Epistemic Counter-Prompt Injected:")
            print(decision.counter_prompt)
        else:
            print("No intervention required. Feed passed directly to downstream analyst.")
        print("=" * 80 + "\n")
